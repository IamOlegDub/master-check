const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('@electric-sql/pglite');
const { randomUUID: uuid } = require('node:crypto');

test('bound invitations, append-only discussions, private files and exactly-once payment confirmation', async () => {
    const db = new PGlite();
    const master = uuid(), client = uuid(), outsider = uuid(), unverified = uuid(), project = uuid(), second = uuid();
    try {
        await db.exec(`create role anon; create role authenticated; create schema auth;
            create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz);
            create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
            grant usage on schema public,auth to authenticated,anon;
            create schema storage; create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
            create table storage.objects(id uuid default gen_random_uuid(),bucket_id text,name text);
            alter table storage.objects enable row level security;
            grant usage on schema storage to anon,authenticated; grant select,insert,update,delete on storage.objects to anon,authenticated;
            create function storage.foldername(text) returns text[] language sql immutable as $$select string_to_array($1,'/')$$;`);
        await db.query("insert into auth.users values($1,'master@example.com',now())", [master]);
        for (const name of fs.readdirSync('supabase/migrations').sort()) await db.exec(fs.readFileSync('supabase/migrations/' + name, 'utf8'));
        await db.query("insert into auth.users values($1,'client@example.com',now()),($2,'other@example.com',now()),($3,'unverified@example.com',null)", [client, outsider, unverified]);
        const as = async (id, role = 'authenticated') => {
            await db.exec('reset role');
            await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id ?? '']);
            await db.exec('set role ' + role);
        };
        const rpc = async (name, ...args) => (await db.query(`select public.${name}(${args.map((_, i) => '$' + (i + 1)).join(',')}) value`, args)).rows[0].value;
        await as(client); await rpc('choose_role', 'CLIENT');
        await as(master); await rpc('register_master', 'test-master');
        await db.query("insert into public.projects(id,user_id,name) values($1,$3,'First'),($2,$3,'Second')", [project, second, master]);
        assert.equal((await rpc('find_project_client', project, ' CLIENT@example.com ')).found, true);
        assert.equal((await rpc('find_project_client', project, 'absent@example.com')).found, false);
        const old = await rpc('make_invite', project, 'client@example.com');
        const invite = await rpc('make_invite', project, 'client@example.com');
        await as(outsider);
        await assert.rejects(() => rpc('find_project_client', project, 'client@example.com'));
        await assert.rejects(() => rpc('accept_invite', invite));
        assert.deepEqual(await rpc('pending_project_invites'), []);
        await as(client);
        assert.equal((await rpc('pending_project_invites')).length, 1);
        await assert.rejects(() => rpc('accept_invite', old));
        assert.equal(await rpc('accept_invite', invite), project);
        assert.equal(await rpc('accept_invite', invite), project);
        assert.deepEqual(await rpc('pending_project_invites'), []);
        await as(master);
        const bad = await rpc('make_invite', second, 'unverified@example.com');
        await as(unverified);
        await assert.rejects(() => rpc('accept_invite', bad));
        await as(master);
        const category = uuid(), service = uuid();
        await db.query("insert into public.service_categories(id,user_id,name) values($1,$2,'Tile')", [category, master]);
        await db.query("insert into public.services(id,user_id,category_id,name,unit,price) values($1,$2,$3,'Tile','m2',1000)", [service, master, category]);
        const estimate = await rpc('project_mutate', project, 'add_item', JSON.stringify({ service_id: service, quantity: 10, version: 0 }), uuid());
        const item = estimate.items[0].id;
        const act = (name, payload, pid = project) => rpc('collaboration_action', pid, name, JSON.stringify(payload));
        const commentId = uuid();
        const comment = { id: commentId, item_id: item, body: 'Please check the tiles', attachments: [] };
        await as(client);
        await act('comment', comment);
        await act('comment', comment);
        assert.equal((await rpc('collaboration_detail', project)).comments.length, 1);
        await assert.rejects(() => act('comment', { ...comment, body: 'Overwrite' }));
        await assert.rejects(() => db.query('delete from public.project_comments where id=$1', [commentId]));
        await assert.rejects(() => db.query("update public.project_comments set body='Changed' where id=$1", [commentId]));
        await assert.rejects(() => act('comment', { ...comment, id: uuid() }, second));
        await as(master);
        await act('comment', { id: uuid(), item_id: item, body: 'The correction is scheduled.' });
        await act('comment', { id: uuid(), body: 'Project-wide note.' });
        await assert.rejects(() => act('comment', { id: uuid(), item_id: item, body: 'Wrong project' }, second));
        await as(client);
        const fileComment = uuid(), path = `${project}/${client}/${fileComment}/${uuid()}`;
        await db.query("insert into storage.objects(bucket_id,name) values('project-attachments',$1)", [path]);
        await act('comment', { id: fileComment, body: '', attachments: [{ path, name: 'photo.png' }] });
        assert.equal((await db.query("select * from storage.objects where name=$1", [path])).rows.length, 1);
        await db.query('delete from storage.objects where name=$1', [path]);
        await db.query("update storage.objects set name='replacement' where name=$1", [path]);
        assert.equal((await db.query('select * from storage.objects where name=$1', [path])).rows.length, 1);
        await assert.rejects(() => act('comment', { id: uuid(), body: '', attachments: [{ path, name: 'stolen.png' }] }));
        await as(master);
        assert.equal((await db.query('select * from storage.objects where name=$1', [path])).rows.length, 1);
        await as(outsider);
        assert.equal((await db.query('select * from public.project_comments')).rows.length, 0);
        assert.equal((await db.query('select * from storage.objects where name=$1', [path])).rows.length, 0);
        await assert.rejects(() => rpc('collaboration_detail', project));
        await assert.rejects(() => act('comment', { id: uuid(), body: 'Intruder' }));
        await assert.rejects(() => db.query("insert into storage.objects(bucket_id,name) values('project-attachments',$1)", [`${project}/${outsider}/${uuid()}/file`]));
        await as(client);
        const notice = { id: uuid(), amount: '1500.25', note: 'Advance', attachments: [] };
        await act('payment_notice', notice);
        await act('payment_notice', notice);
        assert.equal((await rpc('workflow_detail', project)).project.paid, 0);
        await assert.rejects(() => act('payment_notice', { ...notice, amount: '1' }));
        await assert.rejects(() => act('payment_notice', { ...notice, id: uuid(), amount: '1.001' }));
        await assert.rejects(() => act('confirm_payment_notice', { id: notice.id }));
        await as(master);
        await assert.rejects(() => act('payment_notice', { ...notice, id: uuid() }));
        await act('confirm_payment_notice', { id: notice.id });
        await act('confirm_payment_notice', { id: notice.id });
        let detail = await rpc('workflow_detail', project);
        assert.equal(detail.project.paid, 1500.25);
        assert.equal(detail.payments.length, 1);
        const receipt = (await rpc('collaboration_detail', project)).notices[0].payment_id;
        assert.equal(receipt, detail.payments[0].id);
        await assert.rejects(() => act('confirm_payment_notice', { id: notice.id }, second));
        await rpc('project_mutate', project, 'payment', JSON.stringify({ version: detail.project.version, amount: '2000', note: 'Cash payment' }), uuid());
        await as(client);
        detail = await rpc('workflow_detail', project);
        assert.equal(detail.project.paid, 3500.25);
        const feed = await rpc('collaboration_detail', project);
        assert.equal(feed.events.filter(e => e.action === 'payment').length, 2);
        assert.equal(feed.events.filter(e => e.action === 'confirm_payment_notice').length, 1);
        await as(master);
        await rpc('project_mutate', project, 'void_payment', JSON.stringify({ version: detail.project.version, payment_id: receipt, note: 'Incorrect amount; recording a correction' }), uuid());
        await act('confirm_payment_notice', { id: notice.id });
        assert.equal((await rpc('workflow_detail', project)).project.paid, 2000);
        await as(null, 'anon');
        await assert.rejects(() => rpc('collaboration_detail', project));
        assert.equal((await db.query('select * from storage.objects where name=$1', [path])).rows.length, 0);
    } finally { await db.close(); }
});